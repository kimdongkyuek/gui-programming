//  화면, 마우스, HDC 같은 이야기는 여기에 전혀 없습니다.
//  오로지 "점을 배열에 넣고 빼는" 일만 합니다. 이렇게 관심사를 나누는 것이 목적입니다.
// ==========================================================================
#include "model.h"

// static 을 붙이면 이 파일 안에서만 보이는 변수가 됩니다.
// W02Win32.cpp 에서 Points 를 직접 건드릴 수 없고, 반드시 아래 함수들을 거쳐야 합니다.
// 이렇게 막아 두면 실수로 배열 범위를 넘는 일이 생기지 않습니다. (캡슐화)
static POINT Points[MODEL_MAX_POINTS];  // 점들을 담아 둘 배열
static int Index = 0;                   // 지금까지 저장된 개수 (= 다음에 넣을 자리)

// [참고] 아래 extern / inline 은 강의노트 원본 그대로입니다. 뜻만 알아 두세요.
//   extern : "이 함수는 다른 파일에서도 부를 수 있다"는 표시. 사실 함수는 기본이 extern 이라
//            안 써도 똑같이 동작합니다. (읽는 사람에게 의도를 알려 주는 용도)
//   inline : "이 함수는 짧으니 호출하지 말고 그 자리에 펼쳐 넣어도 된다"는 컴파일러 힌트.
//            빼도 동작은 같습니다. 지금 단계에서는 없다고 생각하고 읽어도 됩니다.

// 저장된 점의 개수를 알려 줍니다.
extern inline int GetNumPoints() {
	return Index;
}

// i 번째 점을 돌려줍니다. (0 <= i < GetNumPoints())
extern inline POINT GetPoint(int i) {
	return Points[i];
}

// 점 하나를 추가합니다. 배열이 꽉 찼으면 아무 일도 하지 않습니다.
//   Points[Index++] = p;  는
//   Points[Index] = p; 를 한 다음 Index 를 1 늘리라는 뜻입니다.
extern void AddPoint(POINT p) {
	if (Index < MODEL_MAX_POINTS)
		Points[Index++] = p;
}

// 마지막에 넣은 점을 하나 지웁니다. (Undo)
// 배열 값을 실제로 지울 필요는 없습니다. 개수만 줄이면 그 뒤는 없는 셈이 됩니다.
extern void DeleteLastPoint() {
	if (Index > 0)
		Index--;
}
